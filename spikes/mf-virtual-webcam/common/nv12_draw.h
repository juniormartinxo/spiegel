// SPIKE — throwaway. Tiny NV12 drawing helpers (rects + 5x7 bitmap text), no GDI, so the
// same code works in the feeder and inside the Frame Server service.
#pragma once
#include <stdint.h>
#include <string.h>

struct Yuv { uint8_t y, u, v; };

// BT.601 limited range.
static inline Yuv RgbToYuv(int r, int g, int b) {
    int y = ((66 * r + 129 * g + 25 * b + 128) >> 8) + 16;
    int u = ((-38 * r - 74 * g + 112 * b + 128) >> 8) + 128;
    int v = ((112 * r - 94 * g - 18 * b + 128) >> 8) + 128;
    return {(uint8_t)y, (uint8_t)u, (uint8_t)v};
}

struct Nv12 {
    uint8_t* y;
    uint8_t* uv;
    int pitch;
    int w, h;
};

static inline void Nv12Fill(const Nv12& f, int x, int y, int w, int h, Yuv c) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > f.w) w = f.w - x;
    if (y + h > f.h) h = f.h - y;
    if (w <= 0 || h <= 0) return;
    for (int r = 0; r < h; r++) memset(f.y + (size_t)(y + r) * f.pitch + x, c.y, w);
    int cx = x / 2, cy = y / 2, cw = (w + 1) / 2, ch = (h + 1) / 2;
    for (int r = 0; r < ch; r++) {
        uint8_t* p = f.uv + (size_t)(cy + r) * f.pitch + cx * 2;
        for (int i = 0; i < cw; i++) { p[2 * i] = c.u; p[2 * i + 1] = c.v; }
    }
}

static const uint8_t* Glyph5x7(char ch) {
    static const uint8_t digits[10][7] = {
        {0x0E,0x11,0x13,0x15,0x19,0x11,0x0E},{0x04,0x0C,0x04,0x04,0x04,0x04,0x0E},
        {0x0E,0x11,0x01,0x02,0x04,0x08,0x1F},{0x1F,0x02,0x04,0x02,0x01,0x11,0x0E},
        {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02},{0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E},
        {0x06,0x08,0x10,0x1E,0x11,0x11,0x0E},{0x1F,0x01,0x02,0x04,0x08,0x08,0x08},
        {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E},{0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C}};
    static const uint8_t letters[26][7] = {
        {0x0E,0x11,0x11,0x1F,0x11,0x11,0x11},{0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E},
        {0x0E,0x11,0x10,0x10,0x10,0x11,0x0E},{0x1C,0x12,0x11,0x11,0x11,0x12,0x1C},
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F},{0x1F,0x10,0x10,0x1E,0x10,0x10,0x10},
        {0x0E,0x11,0x10,0x17,0x11,0x11,0x0F},{0x11,0x11,0x11,0x1F,0x11,0x11,0x11},
        {0x0E,0x04,0x04,0x04,0x04,0x04,0x0E},{0x07,0x02,0x02,0x02,0x02,0x12,0x0C},
        {0x11,0x12,0x14,0x18,0x14,0x12,0x11},{0x10,0x10,0x10,0x10,0x10,0x10,0x1F},
        {0x11,0x1B,0x15,0x15,0x11,0x11,0x11},{0x11,0x11,0x19,0x15,0x13,0x11,0x11},
        {0x0E,0x11,0x11,0x11,0x11,0x11,0x0E},{0x1E,0x11,0x11,0x1E,0x10,0x10,0x10},
        {0x0E,0x11,0x11,0x11,0x15,0x12,0x0D},{0x1E,0x11,0x11,0x1E,0x14,0x12,0x11},
        {0x0F,0x10,0x10,0x0E,0x01,0x01,0x1E},{0x1F,0x04,0x04,0x04,0x04,0x04,0x04},
        {0x11,0x11,0x11,0x11,0x11,0x11,0x0E},{0x11,0x11,0x11,0x11,0x11,0x0A,0x04},
        {0x11,0x11,0x11,0x15,0x15,0x15,0x0A},{0x11,0x11,0x0A,0x04,0x0A,0x11,0x11},
        {0x11,0x11,0x11,0x0A,0x04,0x04,0x04},{0x1F,0x01,0x02,0x04,0x08,0x10,0x1F}};
    static const uint8_t colon[7] = {0,0x0C,0x0C,0,0x0C,0x0C,0};
    static const uint8_t dot[7] = {0,0,0,0,0,0x0C,0x0C};
    static const uint8_t dash[7] = {0,0,0,0x1F,0,0,0};
    static const uint8_t eq[7] = {0,0,0x1F,0,0x1F,0,0};
    static const uint8_t slash[7] = {0x01,0x01,0x02,0x04,0x08,0x10,0x10};
    static const uint8_t space[7] = {0};
    if (ch >= '0' && ch <= '9') return digits[ch - '0'];
    if (ch >= 'a' && ch <= 'z') ch = (char)(ch - 32);
    if (ch >= 'A' && ch <= 'Z') return letters[ch - 'A'];
    switch (ch) {
    case ':': return colon;
    case '.': return dot;
    case '-': return dash;
    case '=': return eq;
    case '/': return slash;
    default: return space;
    }
}

// Draws text with a solid background box so it stays legible over any pattern.
static inline void Nv12Text(const Nv12& f, int x, int y, int scale, const char* s, Yuv fg, Yuv bg) {
    int n = (int)strlen(s);
    Nv12Fill(f, x - scale * 2, y - scale * 2, n * 6 * scale + scale * 3, 7 * scale + scale * 4, bg);
    for (int i = 0; i < n; i++) {
        const uint8_t* g = Glyph5x7(s[i]);
        for (int r = 0; r < 7; r++)
            for (int c = 0; c < 5; c++)
                if (g[r] & (0x10 >> c)) Nv12Fill(f, x + (i * 6 + c) * scale, y + r * scale, scale, scale, fg);
    }
}
